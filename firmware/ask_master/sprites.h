// ============================================================================
// 24x24 4-color sprites
//
// Stored as 24 strings of exactly 24 chars each. Chars map to color levels
// used by the renderer at draw time, modulated by the screen accent color:
//
//   '.'  level 0 — transparent (skip)
//   '+'  level 1 — dim   (~40% accent)
//   '='  level 2 — mid   (~70% accent)
//   '#'  level 3 — bright (100% accent)
//
// The renderer reads chars at runtime (PROGMEM array of strings) and writes
// one pixel per cell. ~600 bytes per sprite — cheap on ESP32 flash, easy to
// iterate art without rebuilding bitmap byte arrays.
// ============================================================================

